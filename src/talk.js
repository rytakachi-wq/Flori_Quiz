// extra:そのときの、ようすに合わせた、ひとこと(ごほうびの、あと少し など)を返す関数
export function createTalker({ textEl, bubbleEl, extra = () => [] }) {
  let timer = 0;
  let last = "";
  const pick = () => {
    const pool = [...TALKS, ...extra()];
    let text = last;
    for (let i = 0; i < 8 && text === last; i += 1) text = pool[Math.floor(Math.random() * pool.length)];
    return text;
  };
  const set = (text) => {
    last = text;
    bubbleEl.classList.remove("talk-change");
    void bubbleEl.offsetWidth; // 動きを、はじめからやりなおす
    textEl.textContent = text;
    bubbleEl.classList.add("talk-change");
  };
  const stop = () => clearInterval(timer);
  return {
    start() {
      stop();
      set(TALKS[0]);
      timer = setInterval(() => set(pick()), TALK_INTERVAL);
    },
    stop,
  };
}
